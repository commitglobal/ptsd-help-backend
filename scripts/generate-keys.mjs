#!/usr/bin/env node
// Generates asset keys from the current S3 config and tool/subtool keys from the mobile app's tool ids.
// Re-run whenever the app adds tools or asset keys: npm run generate:keys
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const s3Dir = path.resolve(process.env.S3_CONTENT_DIR ?? path.join(root, '..', 's3-content'));
const mobileDir = path.resolve(process.env.MOBILE_DIR ?? path.join(root, '..', 'ptsd-help-mobile'));

const readJson = (file) => JSON.parse(fs.readFileSync(file, 'utf8'));

const mapping = readJson(path.join(s3Dir, 'config', 'CMSToolsAssetsMapping_RO_ro.json'));
const useTools = fs.readFileSync(path.join(mobileDir, 'hooks', 'useTools.ts'), 'utf8');

const enumValues = (name) => {
  const match = useTools.match(new RegExp(`enum ${name} \\{([\\s\\S]*?)\\}`));
  if (!match) throw new Error(`enum ${name} not found in useTools.ts`);
  return [...match[1].matchAll(/=\s*'([^']+)'/g)].map((m) => m[1]);
};

const assetKeys = Object.keys(mapping);
const toolKeys = enumValues('ToolIds');
const subtoolKeys = enumValues('ToolSubcategoriesIds');
const appToolIds = [...new Set([...toolKeys, ...subtoolKeys])];

const write = (rel, content) => {
  const file = path.join(root, rel);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
  console.log(`wrote ${rel}`);
};

const list = (values) => JSON.stringify(values, null, 2);

write(
  'src/constants/keys.ts',
  `// Generated by scripts/generate-keys.mjs — do not edit by hand.
export const ASSET_KEYS: readonly string[] = ${list(assetKeys)};

export const TOOL_KEYS: readonly string[] = ${list(toolKeys)};

export const SUBTOOL_KEYS: readonly string[] = ${list(subtoolKeys)};

export const APP_TOOL_IDS: readonly string[] = ${list(appToolIds)};
`
);

// One Tool asset document per (country, key); the file is localized, key and country are not.
write(
  'src/api/tool-asset/content-types/tool-asset/schema.json',
  JSON.stringify(
    {
      kind: 'collectionType',
      collectionName: 'tool_assets',
      info: {
        singularName: 'tool-asset',
        pluralName: 'tool-assets',
        displayName: 'Tool asset',
        description: 'Media file for a tool or symptom, one entry per country and key',
      },
      options: { draftAndPublish: false },
      pluginOptions: { i18n: { localized: true } },
      attributes: {
        key: { type: 'enumeration', enum: assetKeys, required: true, pluginOptions: { i18n: { localized: false } } },
        country: {
          type: 'relation',
          relation: 'manyToOne',
          target: 'api::country.country',
          pluginOptions: { i18n: { localized: false } },
        },
        file: {
          type: 'media',
          multiple: false,
          required: true,
          allowedTypes: ['images', 'videos', 'audios', 'files'],
          pluginOptions: { i18n: { localized: true } },
        },
      },
    },
    null,
    2
  ) + '\n'
);

write(
  'src/components/shared/subtool-flag.json',
  JSON.stringify(
    {
      collectionName: 'components_shared_subtool_flags',
      info: { displayName: 'Subtool flag' },
      attributes: {
        key: { type: 'enumeration', enum: subtoolKeys, required: true },
        enabled: { type: 'boolean', default: true, required: true },
      },
    },
    null,
    2
  ) + '\n'
);

write(
  'src/components/shared/tool-flag.json',
  JSON.stringify(
    {
      collectionName: 'components_shared_tool_flags',
      info: { displayName: 'Tool flag' },
      attributes: {
        key: { type: 'enumeration', enum: toolKeys, required: true },
        enabled: { type: 'boolean', default: true, required: true },
        subcategories: { type: 'component', repeatable: true, component: 'shared.subtool-flag' },
      },
    },
    null,
    2
  ) + '\n'
);
